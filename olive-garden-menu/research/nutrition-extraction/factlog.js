// Writes research/products/<slug>/FACT_VERIFICATION.md for item pages from the
// shared data + central official rows, plus page-specific extra facts.
// Usage: node research/nutrition-extraction/factlog.js <slug> [<slug>...]
const ROOT = process.cwd();
const fs = require("fs");
const { createJiti } = require(ROOT + "/node_modules/jiti");
const j = createJiti(ROOT + "/x.js", { alias: { "@": ROOT } });
const { productPages } = j(ROOT + "/content/menu/product-pages/index.ts");
const { menuOfferings } = j(ROOT + "/content/menu/offerings/index.ts");
const { offeringNutritionMap: N, offeringAllergenMap: A } = j(ROOT + "/content/menu/nutrition/offering-map.ts");
const { nutritionGuideRows: NR } = j(ROOT + "/content/menu/nutrition/nutrition-guide.ts");
const { allergenGuideRows: AR } = j(ROOT + "/content/menu/nutrition/allergen-guide.ts");

const EXTRA = {
  calamari: [
    ["Two sauces included", "Marinara and spicy ranch, both listed as \"add ...\" rows under Calamari in the nutrition guide (p. 2) and named in the menu description", "2026-11-11 / 2026-11-15"],
    ["Seafood starters", "Calamari and Shrimp Fritto Misto are the two seafood items of the 10 online appetizers (appetizers category data)", "2026-11-11"],
  ],
  "toasted-ravioli": [
    ["Filling", "Seasoned beef (menu description)", "2026-11-11"],
    ["Catering version", "\"Toasted Beef Ravioli (Serves 4 - 6)\" on the catering menu; separate product record `toasted-beef-ravioli`; linked, no price in the text", "2026-11-12"],
  ],
  "stuffed-ziti-fritta": [
    ["Two sauces included", "Alfredo and marinara: \"add alfredo\" (220) and \"add marinara\" (35) rows under Stuffed Ziti Fritta, nutrition guide pp. 2-3", "2026-11-15"],
    ["Fewest calories of fried/baked starters", "500 is the lowest of the 8 fried/baked appetizers (shared data; same claim as /appetizers)", "2026-11-11"],
    ["Vegetarian label", "Not marked (V) on the online menu (no suitability claim made)", "2026-11-11"],
  ],
  breadsticks: [
    ["Pack prices", "6 = $4.99, 12 = $7.29, baked or unbaked (offering options, online pickup)", "2026-11-11"],
    ["Plain breadstick", "130 calories, \"Breadstick, plain (no garlic topping, 1 ea.)\", nutrition guide p. 4 (text only)", "2026-11-15"],
    ["Included with meals", "Classic entrées include soup or salad + 2 breadsticks; Famous House Salad includes 2 breadsticks (research/menu/OFFICIAL_FACTS_LOG.md)", "2026-11-11"],
    ["Vegetarian label", "Official name \"Breadsticks (V)\": Olive Garden's own label, quoted as such", "2026-11-11"],
  ],
};

const fmt = (v) => (v === null ? "—" : typeof v === "number" ? String(v) : `less than ${v.lessThan}`);
for (const slug of process.argv.slice(2)) {
  const page = productPages.find((p) => p.slug === slug);
  const o = menuOfferings.find((x) => x.id === page.primaryOfferingId);
  const nm = N[o.id], am = A[o.id];
  const row = NR.find((r) => r.id === nm.rowId);
  const adds = NR.filter((r) => r.addOnFor === row.id);
  const arow = AR.find((r) => r.id === am.rowId);
  const p0 = o.prices[0];
  const cols = ["calories", "caloriesFromFat", "totalFat", "saturatedFat", "transFat", "cholesterol", "sodium", "totalCarbohydrates", "dietaryFiber", "sugars", "protein"];
  const md = `# ${o.displayName}: Fact Verification

Page: \`/menu/${slug}\` (\`content/menu/product-pages/${slug}.ts\`), status \`${page.status}\`.
Internal record: the reference restaurant may be named here, never on the site.
Generated by \`research/nutrition-extraction/factlog.js\` on 2026-11-18, then reviewed.

## 1. Shared menu data (single source of truth)

| Fact | Value | Source | Checked |
|---|---|---|---|
| Official name | ${o.officialName} | ${p0.sourceUrl} | ${o.verifiedAt} |
| Price (online pickup, reference restaurant) | $${p0.amount.toFixed(2)} | same item page | ${p0.checkedAt} (shown as November 2026; not re-checked since) |
| Calories | ${o.calories} ${o.caloriesBasis} | official (${o.caloriesValueBasis}) | ${o.verifiedAt} |
| Serving | ${o.servingSize} | item page | ${o.verifiedAt} |
| Description (paraphrased) | ${o.description} | item page | ${o.verifiedAt} |
${o.options.length ? o.options.map((x) => `| Option | ${x.label}: $${x.price?.toFixed(2)}, ${x.calories} Cal${x.caloriesFormula ? ` (calc. ${x.caloriesFormula})` : ""} | item page | ${p0.checkedAt} |`).join("\n") + "\n" : ""}
## 2. Official U.S. nutrition guide (US_101926, owner-supplied 2026-11-15)

Mapping: \`${nm.status}\`${nm.note ? ` (${nm.note})` : ""}.

| Row (p. ${row.page}, ${row.section}) | ${cols.join(" | ")} |
|---|${cols.map(() => "---:").join("|")}|
| ${row.label} | ${cols.map((c) => fmt(row.values[c])).join(" | ")} |
${adds.map((a) => `| ${a.label} | ${cols.map((c) => fmt(a.values[c])).join(" | ")} |`).join("\n")}

**Calories check:** our ${o.calories} = guide ${row.values.calories} (same serving basis). No conflict.

## 3. Official U.S. allergen guide (US_101926)

Mapping: \`${am.status}\`. Row "${arow.label}", p. ${arow.page}, ${arow.section}:
prep ${[arow.prep.friedInSoyOil && "fried in soy oil", arow.prep.grilled && "grilled"].filter(Boolean).join(", ") || "none marked"};
contains **${arow.contains.join(", ") || "none marked"}**.

## 4. Other facts used on the page

| Fact | Evidence | Checked |
|---|---|---|
${(EXTRA[slug] || []).map((r) => `| ${r.join(" | ")} |`).join("\n")}

## 5. Calculations shown ("Calc.")

${adds.length ? `- With sauce${adds.length > 1 ? "s" : ""}: ${row.values.calories} + ${adds.map((a) => a.values.calories).join(" + ")} = ${row.values.calories + adds.reduce((s, a) => s + a.values.calories, 0)}\n` : ""}- Share of a 2,000-calorie day: ${o.calories} ÷ 2,000 = ${Math.round((o.calories / 2000) * 100)}%
${o.options.length ? o.options.filter((x) => /^\d+/.test(x.label)).map((x) => `- ${x.label}: $${x.price.toFixed(2)} ÷ ${x.label.match(/^\d+/)[0]} = $${(x.price / Number(x.label.match(/^\d+/)[0])).toFixed(2)} each`).join("\n") + "\n" : ""}
## 6. Not verified / not shown

- Customization options: not verified, so not shown (owner decision 2026-11-18).
- Piece count / servings per order: ${/breadsticks/.test(slug) ? "counts are in the option names (6 or 12)" : "not stated by Olive Garden"}.
- Vegetarian suitability: no claim beyond Olive Garden's own (V) label.
- Price not re-checked after ${p0.checkedAt} (official site blocked from our network).

## 7. Status

Preview (2026-11-18): local development and testing only; waiting for the owner's visual review and approval (\`visualReview: "missing"\`, \`ownerApprovedAt: null\`).
`;
  fs.mkdirSync(`${ROOT}/research/products/${slug}`, { recursive: true });
  fs.writeFileSync(`${ROOT}/research/products/${slug}/FACT_VERIFICATION.md`, md);
  console.log("written", slug);
}
