// Writes research/products/<slug>/FACT_VERIFICATION.md for version-aware item
// pages (Phase 4) and for pages whose hero photo is omitted. Every version is
// logged with its own official nutrition and allergen row.
// Usage: node research/nutrition-extraction/factlog-versions.js <slug> [<slug>...]
const ROOT = process.cwd();
const fs = require("fs");
const { createJiti } = require(ROOT + "/node_modules/jiti");
const j = createJiti(ROOT + "/x.js", { alias: { "@": ROOT } });
const { productPages } = j(ROOT + "/content/menu/product-pages/index.ts");
const { menuOfferings } = j(ROOT + "/content/menu/offerings/index.ts");
const { offeringNutritionMap: N, offeringAllergenMap: A } = j(ROOT + "/content/menu/nutrition/offering-map.ts");
const { nutritionGuideRows: NR } = j(ROOT + "/content/menu/nutrition/nutrition-guide.ts");
const { allergenGuideRows: AR } = j(ROOT + "/content/menu/nutrition/allergen-guide.ts");

const cols = ["calories", "totalFat", "saturatedFat", "sodium", "totalCarbohydrates", "sugars", "protein"];
const fmt = (v) => (v === null || v === undefined ? "—" : typeof v === "number" ? String(v) : `less than ${v.lessThan}`);

for (const slug of process.argv.slice(2)) {
  const page = productPages.find((p) => p.slug === slug);
  const o = menuOfferings.find((x) => x.id === page.primaryOfferingId);
  const p0 = o.prices[0];
  const versions = page.versions && page.versions.length
    ? page.versions
    : [{ key: "single", label: o.displayName, price: p0.amount, calories: o.calories, nutritionRowId: N[o.id].rowId, allergenRowId: A[o.id].rowId }];
  const rows = versions.map((v) => ({ v, n: NR.find((r) => r.id === v.nutritionRowId), a: AR.find((r) => r.id === v.allergenRowId) }));
  const sizes = (page.sizeOfferingIds || []).map((id) => menuOfferings.find((x) => x.id === id));
  const md = `# ${o.displayName}: Fact Verification

Page: \`/menu/${slug}\`, status \`${page.status}\`${page.versions ? ", version-aware layout (Phase 4, owner approval 2026-11-18)" : ""}.
Internal record: the reference restaurant may be named here, never on the site.
Generated by \`research/nutrition-extraction/factlog-versions.js\` on 2026-11-18, then reviewed.

## 1. Shared menu data

| Fact | Value | Source | Checked |
|---|---|---|---|
| Official name | ${o.officialName} | ${p0.sourceUrl} | ${o.verifiedAt} |
| Listed price (online pickup) | $${p0.amount.toFixed(2)} | same item page | ${p0.checkedAt} (shown as November 2026) |
| Calories (menu) | ${o.calories}${o.caloriesMax ? `-${o.caloriesMax}` : ""} ${o.caloriesBasis} | item page | ${o.verifiedAt} |
| Option prices | ${o.options.length ? o.options.map((x) => `${x.label} $${x.price?.toFixed(2)} (${x.calories})`).join("; ") : "one listed price for all versions"} | item page | ${p0.checkedAt} |
| Nutrition mapping of the offering | \`${N[o.id].status}\`${N[o.id].note ? `: ${N[o.id].note}` : ""} | offering-map.ts | 2026-11-15 |
${sizes.map((s) => `| Size: ${s.displayName} | $${s.prices[0]?.amount.toFixed(2)}, ${s.calories}${s.caloriesMax ? `-${s.caloriesMax}` : ""} cal, ${s.servingSize} | shared data | ${s.verifiedAt} |`).join("\n")}

## 2. Versions and their official rows (US_101926)

| Version | Price | Calories | Nutrition row | ${cols.slice(1).join(" | ")} | Allergen row | Contains | Prep |
|---|---:|---:|---|${cols.slice(1).map(() => "---:").join("|")}|---|---|---|
${rows.map(({ v, n, a }) => `| ${v.label} | $${v.price.toFixed(2)} | ${v.calories} | ${n ? `p. ${n.page} "${n.label}" (${n.values.calories})` : "none (calories from the online menu only)"} | ${cols.slice(1).map((c) => (n ? fmt(n.values[c]) : "—")).join(" | ")} | ${a ? `p. ${a.page} "${a.label}"` : `none (${(A[o.id] || {}).status === "not-covered" ? "the guide does not cover to-go drinks" : "not listed separately"})`} | ${a ? a.contains.join(", ") : "—"} | ${a ? [a.prep.friedInSoyOil && "fried in soy oil", a.prep.grilled && "grilled"].filter(Boolean).join(", ") || "—" : "—"} |`).join("\n")}

**Calories check:** ${rows.map(({ v, n }) => (n ? `${v.label}: ${v.calories} = guide ${n.values.calories}` : `${v.label}: no row, menu value ${v.calories} shown alone`)).join("; ")}.
The build check (\`lib/product-pages.ts\`) also verifies each version's price and calories against the shared offering data.

## 3. Image

${page.heroImageOmitted ? `Hero photo omitted on the item page: ${page.heroImageOmitted} The shared photo mapping is unchanged (menu cards elsewhere still use it).` : "Existing owner photo reused as mapped (permanent owner instruction 2026-11-18)."}

## 4. Not verified / not shown

- Customization options beyond the listed versions: not shown.
- Price not re-checked after ${p0.checkedAt} (official site blocked from our network).
${rows.some((x) => !x.a) ? "- No official allergen row for the version(s) marked \"none\"; the page says so and shows no allergen marks. Checklist `nutritionAndAllergens` = `partial`.\n" : ""}${rows.some((x) => !x.n) ? "- A version without its own nutrition row shows calories only; the checklist item `nutritionAndAllergens` is `partial`, so the page cannot be published until the owner decides.\n" : ""}
## 5. Status

Preview (2026-11-18): waiting for the owner's visual review and approval.
`;
  fs.mkdirSync(`${ROOT}/research/products/${slug}`, { recursive: true });
  fs.writeFileSync(`${ROOT}/research/products/${slug}/FACT_VERIFICATION.md`, md);
  console.log("written", slug);
}
