// Writes research/products/<slug>/FACT_VERIFICATION.md for the complete-coverage
// pages (owner decisions 2026-11-19): detail-only soups, drinks without their
// own guide row, kids pasta meals (calculated), bundles and combinations.
// Handles pages without a nutrition or allergen row (disclosure instead).
// Usage: node research/nutrition-extraction/factlog-coverage.js <slug> [<slug>...]
const ROOT = process.cwd();
const fs = require("fs");
const { createJiti } = require(ROOT + "/node_modules/jiti");
const j = createJiti(ROOT + "/x.js", { alias: { "@": ROOT } });
const { productPages } = j(ROOT + "/content/menu/product-pages/index.ts");
const { allOfferings, detailNutritionMap, detailAllergenMap } = j(ROOT + "/content/menu/detail-items.ts");
const gen = j(ROOT + "/content/menu/nutrition/offering-map.ts");
const { nutritionGuideRows: NR } = j(ROOT + "/content/menu/nutrition/nutrition-guide.ts");
const { allergenGuideRows: AR } = j(ROOT + "/content/menu/nutrition/allergen-guide.ts");
const N = { ...gen.offeringNutritionMap, ...detailNutritionMap };
const A = { ...gen.offeringAllergenMap, ...detailAllergenMap };

const off = (id) => allOfferings.find((x) => x.id === id);
const cal = (o) => `${o.calories ?? "—"}${o.caloriesMax ? `-${o.caloriesMax}` : ""}`;
const map = (m) => (m ? `\`${m.status}\`${m.rowId ? ` (${m.rowId})` : ""}${m.note ? `: ${m.note}` : ""}` : "none");
const row = (id) => NR.find((r) => r.id === (N[id] || {}).rowId && ["exact", "same-item"].includes(N[id].status));
const arow = (id) => AR.find((r) => r.id === (A[id] || {}).rowId && ["exact", "same-item"].includes(A[id].status));

for (const slug of process.argv.slice(2)) {
  const page = productPages.find((p) => p.slug === slug);
  if (!page) throw new Error(`unknown slug ${slug}`);
  const o = off(page.primaryOfferingId);
  const p0 = o.prices[0];
  const sizes = [...(page.sizeOfferingIds || []), ...(page.equivalentOfferingIds || [])].map(off);
  const n = row(o.id);
  const a = arow(o.id);
  const md = `# ${o.displayName}: Fact Verification

Page: \`/menu/${slug}\`, status \`${page.status}\` (complete menu coverage, owner decisions 2026-11-19).
Internal record: the reference restaurant may be named here, never on the site.
Generated by \`research/nutrition-extraction/factlog-coverage.js\` on 2026-11-19, then reviewed.

## 1. Shared menu data

| Fact | Value | Source | Checked |
|---|---|---|---|
| Official name | ${o.officialName} | ${p0.sourceUrl} | ${o.verifiedAt} |
| Listed price (online pickup) | $${p0.amount.toFixed(2)} | same item page | ${p0.checkedAt} (shown as November 2026) |
| Calories | ${cal(o)} ${o.caloriesBasis ?? ""} (basis: ${o.caloriesValueBasis}) | ${o.caloriesSourceUrl ?? "item page"} | ${o.verifiedAt} |
${o.caloriesFormula ? `| Calculation | ${o.caloriesFormula} | official component values | ${o.verifiedAt} |\n` : ""}| Serving | ${o.servingSize ?? "—"} | item page | ${o.verifiedAt} |
| Options | ${(o.options || []).length ? o.options.map((x) => `${x.label} $${x.price?.toFixed(2)} (${x.calories}${x.caloriesMax ? `-${x.caloriesMax}` : ""})`).join("; ") : "none listed"} | item page | ${p0.checkedAt} |
| Nutrition mapping | ${map(N[o.id])} | offering-map.ts / detail-items.ts | 2026-11-19 |
| Allergen mapping | ${map(A[o.id])} | offering-map.ts / detail-items.ts | 2026-11-19 |
${sizes.map((s) => `| Size / same dish: ${s.officialName} | $${s.prices[0]?.amount.toFixed(2)}, ${cal(s)} cal, ${s.servingSize}; nutrition ${map(N[s.id])} | shared data | ${s.verifiedAt} |`).join("\n")}

## 2. Official rows shown (US_101926)

- Nutrition: ${n ? `p. ${n.page} "${n.label}" (${n.values.calories} calories) = menu ${o.calories}` : "no exact row; the page shows the disclosure below and no other nutrient values."}
- Allergens: ${a ? `p. ${a.page} "${a.label}": contains ${a.contains.join(", ") || "none marked"}` : "no row; the page shows the disclosure below and no allergen marks."}
${(page.versions || []).map((v) => `- Version ${v.label}: $${v.price.toFixed(2)}, ${v.calories} cal, nutrition row ${v.nutritionRowId ?? "none"}, allergen row ${v.allergenRowId ?? "none"}`).join("\n")}

${page.nutritionUnavailableNote ? `**Nutrition disclosure on the page:** ${page.nutritionUnavailableNote}\n\n` : ""}${page.allergenUnavailableNote ? `**Allergen disclosure on the page:** ${page.allergenUnavailableNote}\n\n` : ""}${page.components ? `## 3. What's included (from the official serving text)\n\n${page.components.map((c) => `- ${c.label}: ${c.quantity}${c.offeringId ? ` (linked: \`${c.offeringId}\`)` : ""}`).join("\n")}\n\nTotals are Olive Garden's own listed totals; parts are never re-added into a new total.\n\n` : ""}## ${page.components ? 4 : 3}. Rating and image

- Rating group: \`${page.ratingProductId ?? page.productId}\`${page.ratingProductId ? " (shared group; existing rating data unchanged)" : ""}.
- Photo: existing owner photo reused as mapped (permanent owner instruction 2026-11-18)${page.heroImageOmitted ? `; hero omitted: ${page.heroImageOmitted}` : ""}.

## ${page.components ? 5 : 4}. Gaps and status

${page.acceptedGaps ? `- Accepted gap (${page.acceptedGaps.checklistKeys.join(", ")}): ${page.acceptedGaps.reason}\n` : ""}- Price not re-checked after ${p0.checkedAt}.
- Status: preview (2026-11-19), waiting for the owner's visual review and approval.
`;
  fs.mkdirSync(`${ROOT}/research/products/${slug}`, { recursive: true });
  fs.writeFileSync(`${ROOT}/research/products/${slug}/FACT_VERIFICATION.md`, md);
}
console.log("written", process.argv.length - 2);
